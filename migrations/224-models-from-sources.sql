INSERT OR REPLACE INTO coaster_sources (coaster_id, field, source, ref) SELECT c.id, 'model', (SELECT l.source FROM open_links l JOIN open_raw o ON o.source = l.source AND o.ref = l.ref AND o.k IN ('product', 'model') JOIN _pm p ON p.manu = c.manu AND p.product = o.v WHERE l.coaster_id = c.id LIMIT 1), 'product (224)' FROM coasters c WHERE c.model IS NULL AND EXISTS (SELECT 1 FROM open_links l JOIN open_raw o ON o.source = l.source AND o.ref = l.ref AND o.k IN ('product', 'model') JOIN _pm p ON p.manu = c.manu AND p.product = o.v WHERE l.coaster_id = c.id);
UPDATE coasters SET model = (SELECT p.model FROM open_links l JOIN open_raw o ON o.source = l.source AND o.ref = l.ref AND o.k IN ('product', 'model') JOIN _pm p ON p.manu = coasters.manu AND p.product = o.v WHERE l.coaster_id = coasters.id ORDER BY CASE l.source WHEN 'coasterpedia' THEN 0 WHEN 'enwiki' THEN 1 ELSE 2 END LIMIT 1) WHERE model IS NULL AND EXISTS (SELECT 1 FROM open_links l JOIN open_raw o ON o.source = l.source AND o.ref = l.ref AND o.k IN ('product', 'model') JOIN _pm p ON p.manu = coasters.manu AND p.product = o.v WHERE l.coaster_id = coasters.id);
